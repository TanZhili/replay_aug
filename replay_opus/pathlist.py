"""Path-list files: how a batch run names every input it draws from.

Source audio, room IRs, microphone IRs, noise recordings and measured speaker models
are each named by a text file holding one path per line, not by a directory. A
directory is the wrong unit for this job: published IR and noise corpora ship their
splits mixed into one tree, an experiment usually needs a subset (and needs the
noise used for training kept away from the noise used for evaluation), and a rescan
silently changes meaning the moment somebody drops a file in. A list is explicit,
diffable, and reusable across runs.
"""

from __future__ import annotations

import locale
import os
from collections.abc import Sequence
from pathlib import Path


def read_text_lines(path: Path) -> list[str]:
    """Read a text file, tolerating the encodings Windows shells produce.

    PowerShell's ``>`` writes UTF-16 and ``Set-Content`` writes the locale code page,
    so a list generated by the documented one-liner is frequently not UTF-8.
    """
    raw = path.read_bytes()
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return raw.decode("utf-16").splitlines()
    try:
        return raw.decode("utf-8-sig").splitlines()
    except UnicodeDecodeError:
        encoding = locale.getpreferredencoding(False)
        return raw.decode(encoding, errors="replace").splitlines()


def read_path_list(
    list_path: str | Path,
    kind: str = "file",
    suffixes: tuple[str, ...] | None = None,
) -> list[Path]:
    """Read a list file into existing paths.

    Blank lines and ``#`` comments are skipped and surrounding quotes are stripped
    (Windows "Copy as path" adds them). Relative entries resolve against the
    directory holding the list, so a list can travel with the data it names.
    Duplicates are dropped and the original order is kept.
    """
    path = Path(list_path)
    if path.is_dir():
        raise ValueError(
            f"{path} is a directory; a {kind} input is a text file with one path per line"
        )
    if not path.is_file():
        raise FileNotFoundError(f"{kind} list not found: {path}")

    paths: list[Path] = []
    seen: set[Path] = set()
    missing: list[str] = []
    bad_suffix: list[str] = []
    allowed = {suffix.lower() for suffix in suffixes} if suffixes else None
    for lineno, raw in enumerate(read_text_lines(path), start=1):
        line = _unquote(raw)
        if not line or line.startswith("#"):
            continue
        entry = Path(line)
        if not entry.is_absolute():
            entry = path.parent / entry
        entry = Path(os.path.normpath(entry))
        if entry in seen:
            continue
        if not entry.is_file():
            missing.append(f"  line {lineno}: {line}")
            continue
        if allowed is not None and entry.suffix.lower() not in allowed:
            bad_suffix.append(f"  line {lineno}: {line}")
            continue
        seen.add(entry)
        paths.append(entry)

    if missing:
        raise FileNotFoundError(
            f"{len(missing)} {kind} path(s) in {path} do not exist:\n{_format_lines(missing)}"
        )
    if bad_suffix:
        expected = " ".join(suffixes or ())
        raise ValueError(
            f"{len(bad_suffix)} {kind} path(s) in {path} have an unsupported suffix"
            f" (expected {expected}):\n{_format_lines(bad_suffix)}"
        )
    if not paths:
        raise ValueError(f"no {kind} paths in {path}")
    return paths


def common_root(paths: Sequence[Path]) -> Path | None:
    """Deepest directory containing all of ``paths``, or ``None`` if there isn't one.

    Computed over the parents so a single-entry list yields its directory rather
    than the file itself. Lists spanning two Windows drives have no common root.
    """
    if not paths:
        return None
    try:
        return Path(os.path.commonpath([str(p.parent) for p in paths]))
    except ValueError:
        return None


def relative_labels(paths: Sequence[Path]) -> list[str]:
    """Name each path by its position under the list's common root.

    These labels are what lands in the manifest, and for input audio they are also
    the RNG key and the output path, so they have to be short and readable. Paths
    with no common root fall back to their file name and get a numeric suffix if
    that collides.
    """
    root = common_root(paths)
    labels = []
    for path in paths:
        try:
            rel = path.relative_to(root) if root is not None else Path(path.name)
        except ValueError:
            rel = Path(path.name)
        labels.append(rel.as_posix())
    return _disambiguate(labels)


def _unquote(line: str) -> str:
    line = line.strip()
    if len(line) >= 2 and line[0] == line[-1] and line[0] in "\"'":
        return line[1:-1].strip()
    return line


def _disambiguate(labels: list[str]) -> list[str]:
    counts: dict[str, int] = {}
    out = []
    for label in labels:
        counts[label] = counts.get(label, 0) + 1
        if counts[label] == 1:
            out.append(label)
            continue
        stem = Path(label)
        out.append(f"{stem.with_suffix('').as_posix()}__{counts[label]}{stem.suffix}")
    return out


def _format_lines(items: list[str]) -> str:
    shown = items[:10]
    extra = len(items) - len(shown)
    tail = f"\n  ... and {extra} more" if extra else ""
    return "\n".join(shown) + tail


__all__ = ["common_root", "read_path_list", "read_text_lines", "relative_labels"]
